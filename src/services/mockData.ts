// Helper to generate past dates
const now = new Date();
const getPastDate = (daysAgo: number, hoursAgo: number = 0, minutesAgo: number = 0) => {
  const d = new Date(
    now.getTime() -
      daysAgo * 24 * 60 * 60 * 1000 -
      hoursAgo * 60 * 60 * 1000 -
      minutesAgo * 60 * 1000
  );
  return d.toISOString();
};

